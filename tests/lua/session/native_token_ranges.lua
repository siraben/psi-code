--[==[psi-test
# Psi's calibrated pi-style heuristic: full == 9, tail == 4, keep == 1.
expect = "9|4|1"
]==]
local s = require("psi.session_manager")
local c = require("psi.context")
s.append_user("12345678")
local root = s.leaf_id()
s.append_user("1234")
s.append_user("123456789")
local full = psi.session_token_estimate_from(1)
local tail = psi.session_token_estimate_from(3)
local keep = c.keep_recent_messages(tail)
c.record_usage(3, { input_tokens = 1000, output_tokens = 10 })
assert(c.estimate_context_tokens().tokens == 1010)
s.append_user("1234")
assert(c.estimate_context_tokens().tokens == 1011)
assert(s.branch(root))
assert(c.estimate_context_tokens().tokens == 2, "sibling usage is not a baseline")
s.append_user("1234")
c.record_usage(2, { input_tokens = 1000 })
assert(s.append_context_edit(root, { content = "0" }))
assert(c.estimate_context_tokens().tokens == 2, "context edits invalidate measured usage")
s.append_system({ role = "system", content = "sys", sections = {}, toolsAdded = {} })
assert(c.estimate_context_tokens().tokens == 3)
return tostring(full) .. "|" .. tostring(tail) .. "|" .. tostring(keep)
